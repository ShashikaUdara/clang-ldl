def render_terminal_ppm(text: str, out_path: Path, scale: int = 4, margin: int = 16) -> Path:
    glyph_w, glyph_h = 5 * scale, 7 * scale
    spacing = scale * 2
    width = margin * 2 + len(text) * (glyph_w + spacing)
    height = margin * 2 + glyph_h
    pixels = bytearray([255]) * (width * height)

    def set_px(x: int, y: int, v: int) -> None:
        if 0 <= x < width and 0 <= y < height:
            pixels[y * width + x] = v

    x = margin
    for ch in text:
        cp = ord(ch)
        if cp < 32 or cp > 126:
            continue
        glyph = FONT5x7[cp - 32]
        for row in range(7):
            for col in range(5):
                if (glyph[row] >> (4 - col)) & 1:
                    for sy in range(scale):
                        for sx in range(scale):
                            set_px(x + col * scale + sx, margin + row * scale + sy, 0)
        x += glyph_w + spacing

    with out_path.open("wb") as f:
        f.write(f"P5\n{width} {height}\n255\n".encode("ascii"))
        f.write(pixels)

    return out_path


def _find_unicode_font(size: int = 48):
    from PIL import ImageFont

    candidates = [
        "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf",
        "/usr/share/fonts/truetype/noto/NotoSansSinhala-Regular.ttf",
        "/usr/share/fonts/truetype/noto/NotoSansDevanagari-Regular.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
        "NotoSans-Regular.ttf",
        "DejaVuSans.ttf",
    ]
    for path in candidates:
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue
    return ImageFont.load_default()


def render_unicode_png(text: str, out_path: Path, font_size: int = 48, margin: int = 24) -> Path:
    """Render Unicode text with a system font (for non-Latin synthetic images)."""
    from PIL import Image, ImageDraw, ImageFont

    font = _find_unicode_font(font_size)
    probe = Image.new("RGB", (1, 1))
    draw = ImageDraw.Draw(probe)
    bbox = draw.textbbox((0, 0), text, font=font)
    text_w = bbox[2] - bbox[0]
    text_h = bbox[3] - bbox[1]
    width = max(160, text_w + margin * 2)
    height = max(80, text_h + margin * 2)

    img = Image.new("RGB", (width, height), color="white")
    draw = ImageDraw.Draw(img)
    draw.text((margin, margin), text, fill="black", font=font)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    img.save(out_path)
    return out_path


