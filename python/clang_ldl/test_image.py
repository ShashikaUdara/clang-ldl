def render_terminal_ppm(text: str, out_path: Path, scale: int = 4, margin: int = 16) -> Path:
    glyph_w, glyph_h = 5 * scale, 7 * scale
    spacing = scale * 2
    width = margin * 2 + len(text) * (glyph_w + spacing)
    height = margin * 2 + glyph_h
    pixels = bytearray([255]) * (width * height)

    def set_px(x: int, y: int, v: int) -> None:
        if 0 <= x < width and 0 <= y < height:
            pixels[y * width + x] = v

    x = margin
    for ch in text:
        cp = ord(ch)
        if cp < 32 or cp > 126:
            continue
        glyph = FONT5x7[cp - 32]
        for row in range(7):
            for col in range(5):
                if (glyph[row] >> (4 - col)) & 1:
                    for sy in range(scale):
                        for sx in range(scale):
                            set_px(x + col * scale + sx, margin + row * scale + sy, 0)
        x += glyph_w + spacing

    with out_path.open("wb") as f:
        f.write(f"P5\n{width} {height}\n255\n".encode("ascii"))
        f.write(pixels)

    return out_path
